package com.pwadeployer.pwa

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import com.pwadeployer.model.DeployFile
import com.pwadeployer.model.PwaValidationResult
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream

/**
 * Inspects user-provided web files. Expects files as-is (complete PWA),
 * but if any required PWA artifact or linkage is missing, automatically generates
 * and injects the missing pieces so the deployed site is always a valid, installable PWA.
 */
object PwaInspectorAndFixer {

    fun inspectAndEnsurePwa(
        rawFiles: List<DeployFile>,
        appName: String,
        themeColorHex: String = "#0D1117"
    ): PwaValidationResult {
        if (rawFiles.isEmpty()) {
            return PwaValidationResult(
                wasCompletePwa = false,
                issuesFound = listOf("No files selected."),
                autoFixesApplied = emptyList(),
                finalFiles = emptyList()
            )
        }

        val mutableFiles = rawFiles.map { it.copy(relativePath = it.relativePath.trimStart('/')) }.toMutableList()
        val issues = mutableListOf<String>()
        val fixes = mutableListOf<String>()

        // 1. Check for index.html at root
        val hasIndexHtml = mutableFiles.any { it.relativePath.equals("index.html", ignoreCase = true) }
        if (!hasIndexHtml) {
            val firstHtmlIndex = mutableFiles.indexOfFirst {
                it.relativePath.endsWith(".html", ignoreCase = true) ||
                    it.relativePath.endsWith(".htm", ignoreCase = true)
            }
            if (firstHtmlIndex != -1) {
                val original = mutableFiles[firstHtmlIndex]
                issues.add("Missing root index.html (found '${original.relativePath}').")
                mutableFiles[firstHtmlIndex] = original.copy(relativePath = "index.html")
                fixes.add("Renamed '${original.relativePath}' to 'index.html' so GitHub Pages serves it at root.")
            } else {
                issues.add("No HTML file found in selection.")
                val fallbackHtml = buildFallbackIndexHtml(appName)
                mutableFiles.add(
                    DeployFile(
                        relativePath = "index.html",
                        content = fallbackHtml.toByteArray(Charsets.UTF_8),
                        isAutoGenerated = true
                    )
                )
                fixes.add("Generated a root 'index.html' wrapper.")
            }
        } else {
            // Normalize casing to index.html if needed
            val idx = mutableFiles.indexOfFirst { it.relativePath.equals("index.html", ignoreCase = true) }
            if (idx != -1 && mutableFiles[idx].relativePath != "index.html") {
                mutableFiles[idx] = mutableFiles[idx].copy(relativePath = "index.html")
            }
        }

        // 2. Check for Web App Manifest file (manifest.json or *.webmanifest)
        val existingManifestFile = mutableFiles.firstOrNull {
            it.relativePath.equals("manifest.json", ignoreCase = true) ||
                it.relativePath.endsWith(".webmanifest", ignoreCase = true)
        }
        val manifestFileName = existingManifestFile?.relativePath ?: "manifest.json"
        if (existingManifestFile == null) {
            issues.add("Missing Web App Manifest (manifest.json).")
            val generatedManifest = generateManifestJson(appName, themeColorHex)
            mutableFiles.add(
                DeployFile(
                    relativePath = "manifest.json",
                    content = generatedManifest.toByteArray(Charsets.UTF_8),
                    isAutoGenerated = true
                )
            )
            fixes.add("Auto-generated 'manifest.json' for installable PWA metadata.")
        }

        // 3. Check for PWA icons if manifest was auto-generated or if icon-192.png/icon-512.png are referenced & missing
        val hasAnyPngIcon = mutableFiles.any {
            it.relativePath.endsWith(".png", ignoreCase = true) ||
                it.relativePath.endsWith(".svg", ignoreCase = true) ||
                it.relativePath.endsWith(".webp", ignoreCase = true)
        }
        if (existingManifestFile == null || !hasAnyPngIcon) {
            val need192 = mutableFiles.none { it.relativePath.equals("icon-192.png", ignoreCase = true) }
            val need512 = mutableFiles.none { it.relativePath.equals("icon-512.png", ignoreCase = true) }
            if (need192 || need512) {
                issues.add("Missing standard 192x192 / 512x512 PWA icons.")
                if (need192) {
                    mutableFiles.add(
                        DeployFile(
                            relativePath = "icon-192.png",
                            content = generateAppIconPng(192, appName, themeColorHex),
                            isAutoGenerated = true
                        )
                    )
                }
                if (need512) {
                    mutableFiles.add(
                        DeployFile(
                            relativePath = "icon-512.png",
                            content = generateAppIconPng(512, appName, themeColorHex),
                            isAutoGenerated = true
                        )
                    )
                }
                fixes.add("Auto-generated 'icon-192.png' and 'icon-512.png' PWA icons.")
            }
        }

        // 4. Check for Service Worker file (sw.js or service-worker.js)
        val existingSwFile = mutableFiles.firstOrNull {
            val name = it.relativePath.lowercase()
            name == "sw.js" || name == "service-worker.js" || name == "serviceworker.js"
        }
        val swFileName = existingSwFile?.relativePath ?: "sw.js"
        if (existingSwFile == null) {
            issues.add("Missing Service Worker script (sw.js).")
            val assetList = mutableFiles.map { "./" + it.relativePath }.distinct()
            val generatedSw = generateServiceWorkerJs(appName, assetList)
            mutableFiles.add(
                DeployFile(
                    relativePath = "sw.js",
                    content = generatedSw.toByteArray(Charsets.UTF_8),
                    isAutoGenerated = true
                )
            )
            fixes.add("Auto-generated offline-ready Service Worker ('sw.js').")
        }

        // 5. Inspect index.html for manifest <link>, viewport <meta>, and serviceWorker registration
        val indexFileIdx = mutableFiles.indexOfFirst { it.relativePath == "index.html" }
        if (indexFileIdx != -1) {
            val indexFile = mutableFiles[indexFileIdx]
            var html = indexFile.content.toString(Charsets.UTF_8)
            var htmlModified = false

            val hasViewport = Regex("""<meta[^>]+name\s*=\s*["']viewport["']""", RegexOption.IGNORE_CASE)
                .containsMatchIn(html)
            val hasManifestLink = Regex("""<link[^>]+rel\s*=\s*["']manifest["']""", RegexOption.IGNORE_CASE)
                .containsMatchIn(html)
            val hasSwRegistration = html.contains("serviceWorker", ignoreCase = true)

            val headInjections = StringBuilder()
            if (!hasViewport) {
                issues.add("index.html is missing a responsive <meta name=\"viewport\"> tag.")
                headInjections.append("\n  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">")
                fixes.add("Injected <meta name=\"viewport\"> into index.html.")
            }
            if (!hasManifestLink) {
                issues.add("index.html does not link to '$manifestFileName'.")
                headInjections.append("\n  <link rel=\"manifest\" href=\"./$manifestFileName\">")
                headInjections.append("\n  <meta name=\"theme-color\" content=\"$themeColorHex\">")
                headInjections.append("\n  <link rel=\"apple-touch-icon\" href=\"./icon-192.png\">")
                fixes.add("Injected <link rel=\"manifest\" href=\"./$manifestFileName\"> into index.html.")
            }

            if (headInjections.isNotEmpty()) {
                htmlModified = true
                html = injectIntoHead(html, headInjections.toString())
            }

            if (!hasSwRegistration) {
                issues.add("index.html does not register a Service Worker.")
                val swScript = """
                    |
                    |  <script>
                    |    if ('serviceWorker' in navigator) {
                    |      window.addEventListener('load', () => {
                    |        navigator.serviceWorker.register('./$swFileName').then((reg) => {
                    |          reg.update().catch(() => {});
                    |          document.addEventListener('visibilitychange', () => {
                    |            if (document.visibilityState === 'visible') reg.update().catch(() => {});
                    |          });
                    |          reg.addEventListener('updatefound', () => {
                    |            val w = reg.installing;
                    |            if (w != null) {
                    |              w.addEventListener('statechange', () => {
                    |                if (w.state === 'installed' && navigator.serviceWorker.controller != null) {
                    |                  w.postMessage(mapOf("type" to "SKIP_WAITING"));
                    |                }
                    |              });
                    |            }
                    |          });
                    |        }).catch(err => console.warn('SW registration failed:', err));
                    |        var refreshing = false;
                    |        navigator.serviceWorker.addEventListener('controllerchange', () => {
                    |          if (!refreshing) {
                    |            refreshing = true;
                    |            window.location.reload();
                    |          }
                    |        });
                    |      });
                    |    }
                    |  </script>
                """.trimMargin()
                htmlModified = true
                html = injectBeforeBodyClose(html, swScript)
                fixes.add("Injected auto-updating Service Worker registration script for './$swFileName' into index.html.")
            }

            if (htmlModified) {
                mutableFiles[indexFileIdx] = indexFile.copy(
                    content = html.toByteArray(Charsets.UTF_8)
                )
            }
        }

        // 6. Add .nojekyll so GitHub Pages serves all files without Jekyll filtering
        if (mutableFiles.none { it.relativePath == ".nojekyll" }) {
            mutableFiles.add(
                DeployFile(
                    relativePath = ".nojekyll",
                    content = ByteArray(0),
                    isAutoGenerated = true
                )
            )
        }

        return PwaValidationResult(
            wasCompletePwa = issues.isEmpty(),
            issuesFound = issues,
            autoFixesApplied = fixes,
            finalFiles = mutableFiles
        )
    }

    private fun injectIntoHead(html: String, injection: String): String {
        val headCloseRegex = Regex("""</head>""", RegexOption.IGNORE_CASE)
        return if (headCloseRegex.containsMatchIn(html)) {
            headCloseRegex.replaceFirst(html, "$injection\n</head>")
        } else {
            val htmlOpenRegex = Regex("""<html[^>]*>""", RegexOption.IGNORE_CASE)
            val htmlOpenMatch = htmlOpenRegex.find(html)
            if (htmlOpenMatch != null) {
                htmlOpenRegex.replaceFirst(html, "${htmlOpenMatch.value}\n<head>$injection\n</head>")
            } else {
                "<head>$injection\n</head>\n$html"
            }
        }
    }

    private fun injectBeforeBodyClose(html: String, injection: String): String {
        val bodyCloseRegex = Regex("""</body>""", RegexOption.IGNORE_CASE)
        return if (bodyCloseRegex.containsMatchIn(html)) {
            bodyCloseRegex.replaceFirst(html, "$injection\n</body>")
        } else {
            "$html\n$injection"
        }
    }

    private fun generateManifestJson(appName: String, themeColorHex: String): String {
        val cleanName = appName.ifBlank { "My PWA" }
        val shortName = if (cleanName.length > 12) cleanName.take(12).trim() else cleanName
        val manifest = JSONObject().apply {
            put("name", cleanName)
            put("short_name", shortName)
            put("start_url", "./index.html")
            put("scope", "./")
            put("display", "standalone")
            put("background_color", themeColorHex)
            put("theme_color", themeColorHex)
            put("description", "$cleanName — Deployed from Android PWA GitHub Deployer")
            val icons = JSONArray().apply {
                put(
                    JSONObject().apply {
                        put("src", "./icon-192.png")
                        put("sizes", "192x192")
                        put("type", "image/png")
                        put("purpose", "any maskable")
                    }
                )
                put(
                    JSONObject().apply {
                        put("src", "./icon-512.png")
                        put("sizes", "512x512")
                        put("type", "image/png")
                        put("purpose", "any maskable")
                    }
                )
            }
            put("icons", icons)
        }
        return manifest.toString(2)
    }

    private fun generateServiceWorkerJs(appName: String, assets: List<String>): String {
        val slug = appName.lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-').ifBlank { "pwa" }
        val cacheName = "$slug-cache-v1"
        val assetListJson = JSONArray(listOf("./") + assets).toString(2)
        return """
            |const CACHE_NAME = '$cacheName';
            |const ASSETS_TO_CACHE = $assetListJson;
            |
            |self.addEventListener('install', (event) => {
            |  event.waitUntil(
            |    caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS_TO_CACHE))
            |  );
            |  self.skipWaiting();
            |});
            |
            |self.addEventListener('activate', (event) => {
            |  event.waitUntil(
            |    caches.keys().then((keys) =>
            |      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
            |    )
            |  );
            |  self.clients.claim();
            |});
            |
            |self.addEventListener('message', (event) => {
            |  if (event.data && event.data.type === 'SKIP_WAITING') {
            |    self.skipWaiting();
            |  }
            |});
            |
            |self.addEventListener('fetch', (event) => {
            |  if (event.request.method !== 'GET') return;
            |  const url = new URL(event.request.url);
            |  const isHtmlOrCore = event.request.mode === 'navigate' || url.pathname.endsWith('.html') || url.pathname.endsWith('.js') || url.pathname.endsWith('.css');
            |
            |  if (isHtmlOrCore) {
            |    event.respondWith(
            |      fetch(event.request).then((response) => {
            |        if (response && response.status === 200) {
            |          const cloned = response.clone();
            |          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, cloned));
            |        }
            |        return response;
            |      }).catch(() => caches.match(event.request))
            |    );
            |    return;
            |  }
            |
            |  event.respondWith(
            |    caches.match(event.request).then((cached) => {
            |      return cached || fetch(event.request).then((response) => {
            |        const cloned = response.clone();
            |        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, cloned));
            |        return response;
            |      }).catch(() => cached);
            |    })
            |  );
            |});
        """.trimMargin()
    }

    private fun buildFallbackIndexHtml(appName: String): String {
        return """
            |<!DOCTYPE html>
            |<html lang="en">
            |<head>
            |  <meta charset="UTF-8">
            |  <meta name="viewport" content="width=device-width, initial-scale=1.0">
            |  <title>$appName</title>
            |  <link rel="manifest" href="./manifest.json">
            |</head>
            |<body>
            |  <h1>$appName</h1>
            |  <p>Progressive Web App deployed via GitHub Pages.</p>
            |</body>
            |</html>
        """.trimMargin()
    }

    private fun generateAppIconPng(sizePx: Int, appName: String, themeColorHex: String): ByteArray {
        val bitmap = Bitmap.createBitmap(sizePx, sizePx, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)

        val bgPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = try {
                Color.parseColor(themeColorHex)
            } catch (_: Exception) {
                Color.parseColor("#0D1117")
            }
            style = Paint.Style.FILL
        }
        val radius = sizePx * 0.22f
        canvas.drawRoundRect(RectF(0f, 0f, sizePx.toFloat(), sizePx.toFloat()), radius, radius, bgPaint)

        val accentPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#58A6FF")
            style = Paint.Style.STROKE
            strokeWidth = sizePx * 0.04f
        }
        val inset = sizePx * 0.06f
        canvas.drawRoundRect(
            RectF(inset, inset, sizePx - inset, sizePx - inset),
            radius * 0.8f,
            radius * 0.8f,
            accentPaint
        )

        val initials = appName.trim()
            .split(Regex("[\\s_-]+"))
            .filter { it.isNotEmpty() }
            .take(2)
            .joinToString("") { it.first().uppercaseChar().toString() }
            .ifEmpty { "PW" }

        val textPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.WHITE
            textSize = sizePx * 0.38f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textAlign = Paint.Align.CENTER
        }
        val textY = (sizePx / 2f) - ((textPaint.descent() + textPaint.ascent()) / 2f)
        canvas.drawText(initials, sizePx / 2f, textY, textPaint)

        val out = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.PNG, 100, out)
        bitmap.recycle()
        return out.toByteArray()
    }
}
