package com.pwadeployer.model

data class DeployFile(
    val relativePath: String,
    val content: ByteArray,
    val isAutoGenerated: Boolean = false
) {
    val sizeBytes: Int get() = content.size

    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is DeployFile) return false
        return relativePath == other.relativePath &&
            content.contentEquals(other.content) &&
            isAutoGenerated == other.isAutoGenerated
    }

    override fun hashCode(): Int {
        var result = relativePath.hashCode()
        result = 31 * result + content.contentHashCode()
        result = 31 * result + isAutoGenerated.hashCode()
        return result
    }
}

