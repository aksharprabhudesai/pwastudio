async function init() {
  bindEvents();

  // Immediately restore saved token & user from localStorage so the user never has to re-enter it
  if (state.token) {
    el.tokenInput.value = state.token;
    renderAuthUI();
    updateUrlPreview();
    updateDeployButtonState();
    verifyAndConnectToken(state.token, true);
  } else {
    updateUrlPreview();
  }

  // Check if shared HTML/text arrived via URL query params (?title=...&text=...)
  const params = new URLSearchParams(window.location.search);
  const sharedText = params.get('text') || params.get('html');
  if (sharedText && sharedText.includes('<')) {
    el.htmlCodeInput.value = sharedText;
    await importRawFiles([
      { relativePath: 'index.html', bytes: textEncoder.encode(sharedText), isAutoGenerated: false }
    ]);
  }
}

