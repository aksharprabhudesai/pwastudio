/* ============================================================================
 * STEP 1: GITHUB AUTHENTICATION
 * ========================================================================== */
async function verifyAndConnectToken(token, silent) {
  el.authError.classList.add('hidden');
  el.saveTokenBtn.disabled = true;
  el.saveTokenBtn.textContent = 'Checking...';

  // Persist immediately so the user never loses their token
  localStorage.setItem(STORAGE_KEY_TOKEN, token);
  state.token = token;

  try {
    const res = await githubFetch('https://api.github.com/user', token);
    if (res.status === 401) {
      // Only clear if GitHub explicitly says 401 Bad credentials
      localStorage.removeItem(STORAGE_KEY_TOKEN);
      localStorage.removeItem(STORAGE_KEY_USER);
      state.token = '';
      state.user = null;
      renderAuthUI();
      showAuthError('Invalid or expired GitHub token (401). Please generate a new token.');
      return;
    }
    if (!res.ok) {
      const errJson = await res.json().catch(() => ({}));
      throw new Error(errJson.message || `GitHub returned HTTP ${res.status}`);
    }
    const user = await res.json();
    state.user = user;
    localStorage.setItem(STORAGE_KEY_USER, JSON.stringify({
      login: user.login,
      name: user.name,
      avatar_url: user.avatar_url
    }));

    renderAuthUI();
    updateUrlPreview();
    updateDeployButtonState();
    if (!silent) showToast(`Saved & connected as @${user.login}`);
  } catch (err) {
    // Keep token in localStorage on offline/network errors so user doesn't have to re-enter it!
    renderAuthUI();
    if (!silent) {
      showAuthError(`Could not verify right now (${err.message}), but token is saved locally.`);
    }
  } finally {
    el.saveTokenBtn.disabled = false;
    el.saveTokenBtn.textContent = 'Connect';
  }
}

