function startPollingPagesStatus(owner, repo, pagesUrl) {
  if (state.pagesPollTimer) clearInterval(state.pagesPollTimer);
  el.pagesStatusDot.classList.remove('live');
  el.pagesStatusText.textContent = 'GitHub Pages is building your PWA (~30–60s)...';

  let checks = 0;
  const checkNow = async () => {
    checks++;
    try {
      const res = await githubFetch(
        `https://api.github.com/repos/${owner}/${repo}/pages`,
        state.token
      );
      if (res.ok) {
        const data = await res.json();
        if (data.status === 'built') {
          el.pagesStatusDot.classList.add('live');
          el.pagesStatusText.textContent = 'Live! Your PWA is built and ready to open & install.';
          clearInterval(state.pagesPollTimer);
          return;
        }
      }
    } catch (_) {}

    if (checks >= 20) {
      clearInterval(state.pagesPollTimer);
      el.pagesStatusDot.classList.add('live');
      el.pagesStatusText.textContent = `Ready at ${pagesUrl}`;
    }
  };

  checkNow();
  state.pagesPollTimer = setInterval(checkNow, 5000);
}

/**
 * Renders a scannable QR code onto the canvas using the public QR Server image API
 * with an offline fallback badge so zero external JS libraries are required.
 */
function drawSimpleQrBadge(canvas, url) {
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  const img = new Image();
  img.crossOrigin = 'anonymous';
  img.onload = () => {
    ctx.drawImage(img, 8, 8, canvas.width - 16, canvas.height - 16);
  };
  img.onerror = () => {
    ctx.fillStyle = '#0D1117';
    ctx.font = 'bold 12px sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText('Live PWA Link Ready', canvas.width / 2, canvas.height / 2);
  };
  img.src = `https://api.qrserver.com/v1/create-qr-code/?size=160x160&data=${encodeURIComponent(url)}`;
}

