/* ============================================================================
 * STEP 2: FILE / FOLDER / ZIP IMPORT & IN-BROWSER UNZIP
 * ========================================================================== */
async function handleSelectedFileList(fileList, isFolder) {
  const imported = [];
  for (const file of fileList) {
    const rawPath = isFolder && file.webkitRelativePath ? file.webkitRelativePath : file.name;
    if (rawPath.includes('.git/') || rawPath.includes('__MACOSX') || file.name === '.DS_Store') {
      continue;
    }

    const buffer = await file.arrayBuffer();
    const bytes = new Uint8Array(buffer);

    if (file.name.toLowerCase().endsWith('.zip') && !isFolder) {
      const unzipped = await extractZipArchive(bytes);
      imported.push(...unzipped);
    } else {
      imported.push({
        relativePath: rawPath.replace(/^\/+/, ''),
        bytes,
        isAutoGenerated: false
      });
    }
  }

  const normalized = stripCommonTopFolder(imported);
  await importRawFiles(normalized);
}

/**
 * Pure client-side ZIP extractor (supports Store [0] and Deflate [8] via browser DecompressionStream).
 */
async function extractZipArchive(zipBytes) {
  const view = new DataView(zipBytes.buffer, zipBytes.byteOffset, zipBytes.byteLength);
  // Locate End of Central Directory (EOCD) signature 0x06054b50
  let eocdOffset = -1;
  for (let i = zipBytes.length - 22; i >= Math.max(0, zipBytes.length - 65557); i--) {
    if (view.getUint32(i, true) === 0x06054b50) {
      eocdOffset = i;
      break;
    }
  }
  if (eocdOffset === -1) {
    throw new Error('Invalid ZIP file');
  }

  const totalEntries = view.getUint16(eocdOffset + 10, true);
  const cdOffset = view.getUint32(eocdOffset + 16, true);

  const results = [];
  let ptr = cdOffset;
  for (let i = 0; i < totalEntries; i++) {
    if (view.getUint32(ptr, true) !== 0x02014b50) break;

    const compressionMethod = view.getUint16(ptr + 10, true);
    const compressedSize = view.getUint32(ptr + 20, true);
    const fileNameLen = view.getUint16(ptr + 28, true);
    const extraLen = view.getUint16(ptr + 30, true);
    const commentLen = view.getUint16(ptr + 32, true);
    const localHeaderOffset = view.getUint32(ptr + 42, true);

    const nameBytes = zipBytes.subarray(ptr + 46, ptr + 46 + fileNameLen);
    const fileName = textDecoder.decode(nameBytes);

    ptr += 46 + fileNameLen + extraLen + commentLen;

    if (fileName.endsWith('/') || fileName.includes('__MACOSX') || fileName.startsWith('.git/')) {
      continue;
    }

    // Read local file header to find actual data start
    const localNameLen = view.getUint16(localHeaderOffset + 26, true);
    const localExtraLen = view.getUint16(localHeaderOffset + 28, true);
    const dataStart = localHeaderOffset + 30 + localNameLen + localExtraLen;
    const compressedSlice = zipBytes.subarray(dataStart, dataStart + compressedSize);

    let fileBytes;
    if (compressionMethod === 0) {
      fileBytes = new Uint8Array(compressedSlice);
    } else if (compressionMethod === 8) {
      const ds = new DecompressionStream('deflate-raw');
      const writer = ds.writable.getWriter();
      writer.write(compressedSlice);
      writer.close();
      const decompressedBuffer = await new Response(ds.readable).arrayBuffer();
      fileBytes = new Uint8Array(decompressedBuffer);
    } else {
      continue;
    }

    results.push({
      relativePath: fileName.replace(/^\/+/, ''),
      bytes: fileBytes,
      isAutoGenerated: false
    });
  }
  return results;
}

function stripCommonTopFolder(files) {
  if (files.length === 0) return files;
  const hasRootIndex = files.some((f) => f.relativePath.toLowerCase() === 'index.html');
  if (hasRootIndex) return files;

  const allHaveSlash = files.every((f) => f.relativePath.includes('/'));
  if (!allHaveSlash) return files;

  const firstPrefix = files[0].relativePath.split('/')[0];
  if (firstPrefix && files.every((f) => f.relativePath.startsWith(firstPrefix + '/'))) {
    return files.map((f) => ({
      ...f,
      relativePath: f.relativePath.slice(firstPrefix.length + 1)
    }));
  }
  return files;
}

async function importRawFiles(files) {
  if (!files || files.length === 0) return;
  state.rawFiles = files;

  // Infer title and repo slug from HTML <title> if present
  const htmlFile = files.find((f) => /\.(html|htm)$/i.test(f.relativePath));
  if (htmlFile) {
    const htmlStr = textDecoder.decode(htmlFile.bytes);
    const titleMatch = htmlStr.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
    if (titleMatch && titleMatch[1].trim()) {
      const extractedTitle = titleMatch[1].trim().slice(0, 50);
      el.appTitleInput.value = extractedTitle;
      const slug = extractedTitle
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
      if (slug) {
        el.repoNameInput.value = slug;
        updateUrlPreview();
      }
    }
  }

  await runPwaInspector();
  updateDeployButtonState();
}

/* ============================================================================
 * SMART PWA INSPECTOR & AUTO-UPGRADER
 * Expects complete PWA as-is; if any piece is missing, auto-generates it!
 * ========================================================================== */
async function runPwaInspector() {
  const appName = el.appTitleInput.value.trim() || 'My Mobile PWA';
  const themeColor = el.themeColorInput.value.trim() || '#0D1117';

  const working = state.rawFiles.map((f) => ({
    relativePath: f.relativePath.replace(/^\/+/, ''),
    bytes: new Uint8Array(f.bytes),
    isAutoGenerated: false
  }));

  const fixes = [];

  // 1. Check root index.html
  let indexIdx = working.findIndex((f) => f.relativePath.toLowerCase() === 'index.html');
  if (indexIdx === -1) {
    const anyHtmlIdx = working.findIndex((f) => /\.(html|htm)$/i.test(f.relativePath));
    if (anyHtmlIdx !== -1) {
      const origName = working[anyHtmlIdx].relativePath;
      working[anyHtmlIdx].relativePath = 'index.html';
      indexIdx = anyHtmlIdx;
      fixes.push(`Renamed '${origName}' to 'index.html' so GitHub Pages serves it at root.`);
    } else {
      const fallbackHtml = `<!DOCTYPE html>\n<html lang="en">\n<head>\n  <meta charset="UTF-8">\n  <title>${appName}</title>\n</head>\n<body>\n  <h1>${appName}</h1>\n</body>\n</html>`;
      working.push({
        relativePath: 'index.html',
        bytes: textEncoder.encode(fallbackHtml),
        isAutoGenerated: true
      });
      indexIdx = working.length - 1;
      fixes.push(`Generated root 'index.html'.`);
    }
  } else {
    working[indexIdx].relativePath = 'index.html';
  }

  // 2. Check Web App Manifest (manifest.json or *.webmanifest)
  const existingManifest = working.find(
    (f) => f.relativePath.toLowerCase() === 'manifest.json' || f.relativePath.toLowerCase().endsWith('.webmanifest')
  );
  const manifestPath = existingManifest ? existingManifest.relativePath : 'manifest.json';

  if (!existingManifest) {
    const manifestObj = {
      name: appName,
      short_name: appName.slice(0, 12).trim() || 'PWA',
      start_url: './index.html',
      scope: './',
      display: 'standalone',
      background_color: themeColor,
      theme_color: themeColor,
      description: `${appName} — Progressive Web App hosted on GitHub Pages`,
      icons: [
        { src: './icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
        { src: './icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' }
      ]
    };
    working.push({
      relativePath: 'manifest.json',
      bytes: textEncoder.encode(JSON.stringify(manifestObj, null, 2)),
      isAutoGenerated: true
    });
    fixes.push(`Auto-generated 'manifest.json' for standalone PWA installation.`);
  }

  // 3. Check 192x192 & 512x512 PWA Icons if manifest was generated
  if (!existingManifest) {
    const has192 = working.some((f) => f.relativePath.toLowerCase() === 'icon-192.png');
    const has512 = working.some((f) => f.relativePath.toLowerCase() === 'icon-512.png');
    if (!has192) {
      const icon192 = await generatePwaIconPngBytes(192, appName, themeColor);
      working.push({ relativePath: 'icon-192.png', bytes: icon192, isAutoGenerated: true });
    }
    if (!has512) {
      const icon512 = await generatePwaIconPngBytes(512, appName, themeColor);
      working.push({ relativePath: 'icon-512.png', bytes: icon512, isAutoGenerated: true });
    }
    if (!has192 || !has512) {
      fixes.push(`Auto-generated 'icon-192.png' and 'icon-512.png' home-screen icons.`);
    }
  }

  // 4. Check Service Worker (sw.js or service-worker.js)
  const existingSw = working.find((f) =>
    ['sw.js', 'service-worker.js', 'serviceworker.js'].includes(f.relativePath.toLowerCase())
  );
  const swPath = existingSw ? existingSw.relativePath : 'sw.js';

  if (!existingSw) {
    const assetUrls = ['./', ...working.map((f) => `./${f.relativePath}`)];
    const cacheSlug = appName.toLowerCase().replace(/[^a-z0-9]+/g, '-') || 'pwa';
    const swCode = [
      `const CACHE_NAME = '${cacheSlug}-v1';`,
      `const ASSETS = ${JSON.stringify(assetUrls, null, 2)};`,
      ``,
      `self.addEventListener('install', (event) => {`,
      `  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS)));`,
      `  self.skipWaiting();`,
      `});`,
      ``,
      `self.addEventListener('activate', (event) => {`,
      `  event.waitUntil(`,
      `    caches.keys().then((keys) =>`,
      `      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))`,
      `    )`,
      `  );`,
      `  self.clients.claim();`,
      `});`,
      ``,
      `self.addEventListener('fetch', (event) => {`,
      `  if (event.request.method !== 'GET') return;`,
      `  event.respondWith(`,
      `    caches.match(event.request).then((cached) => cached || fetch(event.request))`,
      `  );`,
      `});`
    ].join('\n');

    working.push({
      relativePath: 'sw.js',
      bytes: textEncoder.encode(swCode),
      isAutoGenerated: true
    });
    fixes.push(`Auto-generated offline Service Worker ('sw.js').`);
  }

  // 5. Inspect index.html for viewport, manifest link, and serviceWorker registration
  let html = textDecoder.decode(working[indexIdx].bytes);
  let htmlModified = false;

  const hasViewport = /<meta[^>]+name\s*=\s*["']viewport["']/i.test(html);
  const hasManifestLink = /<link[^>]+rel\s*=\s*["']manifest["']/i.test(html);
  const hasSwRegister = /serviceWorker/i.test(html);

  let headAdditions = '';
  if (!hasViewport) {
    headAdditions += `\n  <meta name="viewport" content="width=device-width, initial-scale=1.0">`;
    fixes.push(`Injected responsive <meta name="viewport"> into index.html.`);
  }
  if (!hasManifestLink) {
    headAdditions += `\n  <link rel="manifest" href="./${manifestPath}">`;
    headAdditions += `\n  <meta name="theme-color" content="${themeColor}">`;
    headAdditions += `\n  <link rel="apple-touch-icon" href="./icon-192.png">`;
    fixes.push(`Injected <link rel="manifest" href="./${manifestPath}"> into index.html.`);
  }

  if (headAdditions) {
    htmlModified = true;
    if (/<\/head>/i.test(html)) {
      html = html.replace(/<\/head>/i, `${headAdditions}\n</head>`);
    } else if (/<html[^>]*>/i.test(html)) {
      html = html.replace(/<html[^>]*>/i, (m) => `${m}\n<head>${headAdditions}\n</head>`);
    } else {
      html = `<head>${headAdditions}\n</head>\n${html}`;
    }
  }

  if (!hasSwRegister) {
    htmlModified = true;
    const swSnippet = `\n  <script>\n    if ('serviceWorker' in navigator) {\n      window.addEventListener('load', () => {\n        navigator.serviceWorker.register('./${swPath}').catch(() => {});\n      });\n    }\n  </script>`;
    if (/<\/body>/i.test(html)) {
      html = html.replace(/<\/body>/i, `${swSnippet}\n</body>`);
    } else {
      html = `${html}\n${swSnippet}`;
    }
    fixes.push(`Injected Service Worker registration script into index.html.`);
  }

  if (htmlModified) {
    working[indexIdx].bytes = textEncoder.encode(html);
  }

  // 6. Add .nojekyll so GitHub Pages serves all files cleanly
  if (!working.some((f) => f.relativePath === '.nojekyll')) {
    working.push({
      relativePath: '.nojekyll',
      bytes: new Uint8Array(0),
      isAutoGenerated: true
    });
  }

  state.wasCompletePwa = fixes.length === 0;
  state.autoFixes = fixes;
  state.finalFiles = working;

  renderFilesUI();
}

async function generatePwaIconPngBytes(size, appName, bgColor) {
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');

  // Background
  ctx.fillStyle = bgColor || '#0D1117';
  ctx.fillRect(0, 0, size, size);

  // Subtle accent border
  ctx.strokeStyle = '#58A6FF';
  ctx.lineWidth = Math.max(4, Math.floor(size * 0.04));
  const inset = size * 0.08;
  ctx.strokeRect(inset, inset, size - inset * 2, size - inset * 2);

  // Initials
  const initials =
    appName
      .trim()
      .split(/[\s_-]+/)
      .filter(Boolean)
      .slice(0, 2)
      .map((w) => w[0].toUpperCase())
      .join('') || 'PW';

  ctx.fillStyle = '#FFFFFF';
  ctx.font = `bold ${Math.floor(size * 0.38)}px -apple-system, BlinkMacSystemFont, sans-serif`;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(initials, size / 2, size / 2 + size * 0.02);

  const blob = await new Promise((resolve) => canvas.toBlob(resolve, 'image/png'));
  const buf = await blob.arrayBuffer();
  return new Uint8Array(buf);
}

