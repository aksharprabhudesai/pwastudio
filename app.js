async function deployToGitHubPages() {
  const token = state.token;
  const owner = state.user?.login;
  const repo = sanitizeRepoName(el.repoNameInput.value);
  const appTitle = el.appTitleInput.value.trim() || repo;

  if (!token || !owner || !repo || state.finalFiles.length === 0) return;

  state.isDeploying = true;
  el.deployError.classList.add('hidden');
  el.resultSection.classList.add('hidden');
  el.deployProgressBox.classList.remove('hidden');
  updateDeployButtonState();

  try {
    setProgress('1/5 Checking or creating public repository...', 15);
    const defaultBranch = await ensurePublicRepo(token, owner, repo, appTitle);

    setProgress(`2/5 Reading '${defaultBranch}' branch reference...`, 30);
    const headCommitSha = await getBranchHeadSha(token, owner, repo, defaultBranch);

    const treeEntries = [];
    const total = state.finalFiles.length;
    for (let i = 0; i < total; i++) {
      const file = state.finalFiles[i];
      const pct = 30 + Math.round(((i + 1) / total) * 40);
      setProgress(`3/5 Uploading (${i + 1}/${total}): ${file.relativePath}`, pct);
      const blobSha = await createGitBlob(token, owner, repo, file.bytes);
      treeEntries.push({
        path: file.relativePath,
        mode: '100644',
        type: 'blob',
        sha: blobSha
      });
    }

    setProgress('4/5 Creating Git tree & commit...', 80);
    const newTreeSha = await createGitTree(token, owner, repo, treeEntries);
    const commitSha = await createGitCommit(
      token,
      owner,
      repo,
      `Deploy PWA (${appTitle}) via Mobile PWA Deployer`,
      newTreeSha,
      headCommitSha
    );
    await updateBranchRef(token, owner, repo, defaultBranch, commitSha);

    setProgress('5/5 Enabling GitHub Pages...', 95);
    const pagesUrl = await enableGitHubPages(token, owner, repo, defaultBranch);

    setProgress('Deployment complete!', 100);
    el.step3Badge.classList.add('done');
    el.step3Badge.textContent = '✓';

    showDeploymentSuccess({
      repoUrl: `https://github.com/${owner}/${repo}`,
      pagesUrl,
      owner,
      repo
    });
  } catch (err) {
    el.deployError.textContent = err.message || 'Deployment failed.';
    el.deployError.classList.remove('hidden');
  } finally {
    state.isDeploying = false;
    el.deployProgressBox.classList.add('hidden');
    updateDeployButtonState();
  }
}

function setProgress(text, percent) {
  el.deployProgressStep.textContent = text;
  el.deployProgressBar.style.width = `${percent}%`;
}

async function ensurePublicRepo(token, owner, repo, appTitle) {
  const checkRes = await githubFetch(`https://api.github.com/repos/${owner}/${repo}`, token);
  if (checkRes.ok) {
    const repoData = await checkRes.json();
    const branch = repoData.default_branch || 'main';
    if (repoData.size === 0) {
      await seedEmptyRepoIfNeeded(token, owner, repo, branch);
    }
    return branch;
  }

  if (checkRes.status !== 404) {
    const err = await checkRes.json().catch(() => ({}));
    throw new Error(`Failed checking repo (${checkRes.status}): ${err.message || ''}`);
  }

  const createRes = await githubFetch('https://api.github.com/user/repos', token, {
    method: 'POST',
    body: JSON.stringify({
      name: repo,
      description: `${appTitle} — Progressive Web App deployed via GitHub Pages`,
      private: false,
      auto_init: true
    })
  });

  if (!createRes.ok) {
    const err = await createRes.json().catch(() => ({}));
    throw new Error(`Could not create repository '${repo}': ${err.message || createRes.status}`);
  }

  const created = await createRes.json();
  return created.default_branch || 'main';
}

async function seedEmptyRepoIfNeeded(token, owner, repo, branch) {
  const refRes = await githubFetch(
    `https://api.github.com/repos/${owner}/${repo}/git/ref/heads/${branch}`,
    token
  );
  if (refRes.ok) return;

  await githubFetch(`https://api.github.com/repos/${owner}/${repo}/contents/.nojekyll`, token, {
    method: 'PUT',
    body: JSON.stringify({
      message: 'Initialize repository',
      content: '',
      branch
    })
  });
}

async function getBranchHeadSha(token, owner, repo, branch) {
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await githubFetch(
      `https://api.github.com/repos/${owner}/${repo}/git/ref/heads/${branch}`,
      token
    );
    if (res.ok) {
      const data = await res.json();
      return data.object.sha;
    }
    if (attempt === 1) {
      await seedEmptyRepoIfNeeded(token, owner, repo, branch);
    }
    await sleep(900);
  }
  throw new Error(`Could not read HEAD of branch '${branch}'.`);
}

async function createGitBlob(token, owner, repo, bytes) {
  const base64 = uint8ArrayToBase64(bytes);
  const res = await githubFetch(`https://api.github.com/repos/${owner}/${repo}/git/blobs`, token, {
    method: 'POST',
    body: JSON.stringify({ content: base64, encoding: 'base64' })
  });
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`Failed uploading file blob: ${err.message || res.status}`);
  }
  const data = await res.json();
  return data.sha;
}

async function createGitTree(token, owner, repo, treeEntries) {
  const res = await githubFetch(`https://api.github.com/repos/${owner}/${repo}/git/trees`, token, {
    method: 'POST',
    body: JSON.stringify({ tree: treeEntries })
  });
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`Failed creating Git tree: ${err.message || res.status}`);
  }
  const data = await res.json();
  return data.sha;
}

async function createGitCommit(token, owner, repo, message, treeSha, parentSha) {
  const res = await githubFetch(`https://api.github.com/repos/${owner}/${repo}/git/commits`, token, {
    method: 'POST',
    body: JSON.stringify({
      message,
      tree: treeSha,
      parents: [parentSha]
    })
  });
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`Failed creating commit: ${err.message || res.status}`);
  }
  const data = await res.json();
  return data.sha;
}

async function updateBranchRef(token, owner, repo, branch, commitSha) {
  const res = await githubFetch(
    `https://api.github.com/repos/${owner}/${repo}/git/refs/heads/${branch}`,
    token,
    {
      method: 'PATCH',
      body: JSON.stringify({ sha: commitSha, force: true })
    }
  );
  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`Failed updating branch ref: ${err.message || res.status}`);
  }
}

async function enableGitHubPages(token, owner, repo, branch) {
  const fallbackUrl =
    repo.toLowerCase() === `${owner.toLowerCase()}.github.io`
      ? `https://${owner}.github.io/`
      : `https://${owner}.github.io/${repo}/`;

  const getRes = await githubFetch(`https://api.github.com/repos/${owner}/${repo}/pages`, token);
  if (getRes.ok) {
    const data = await getRes.json();
    return data.html_url || fallbackUrl;
  }

  const postRes = await githubFetch(`https://api.github.com/repos/${owner}/${repo}/pages`, token, {
    method: 'POST',
    body: JSON.stringify({
      source: { branch, path: '/' }
    })
  });

  if (postRes.ok) {
    const data = await postRes.json().catch(() => ({}));
    return data.html_url || fallbackUrl;
  }

  return fallbackUrl;
}

